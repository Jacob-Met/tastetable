import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.TASTETABLE_PLAYWRIGHT_MODULE || 'playwright');
import { createVisitRecord, updateVisitRecord, makeVisitRecordFile } from '../static/visit_record.mjs';
await mkdir('docs/multi-record-history',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.TASTETABLE_REVIEW_CHROMIUM,headless:true,chromiumSandbox:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[], requests=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(r.method()==='POST')requests.push({url:r.url(),body:r.postData()});});
try {
 await page.goto(process.env.TASTETABLE_REVIEW_URL || 'http://127.0.0.1:8853');
 await page.locator('#sampleBtn').click();
 await page.locator('#results').waitFor({state:'visible'});
 const originalNames=await page.locator('.scheduled-pick h4').allTextContents();
 const dl=page.waitForEvent('download'); await page.locator('#saveWeek').click(); const download=await dl;
 const weekText=await readFile(await download.path(),'utf8');
 let record=createVisitRecord(weekText,'Prior family week.json');
 record=updateVisitRecord(record,'pick-0',{outcome:'went',date:'2026-10-25',note:'PRIVATE secret care note'});
 record=updateVisitRecord(record,'pick-1',{outcome:'did_not_go',date:'2026-10-25'});
 const payload={name:'prior-visits.json',mimeType:'application/json',buffer:Buffer.from(makeVisitRecordFile(record).text)};
 await page.locator('#visitHistory summary').click();
 await page.locator('#visitHistory input').setInputFiles(payload);
 await page.locator('[data-history-preview]').waitFor({state:'visible'});
 assert.equal(await page.locator('.prior-visit').count(),0);
 await page.locator('[data-history-use]').click();
 assert.equal(await page.locator('.prior-visit').count(),1);
 assert.match(await page.locator('.prior-visit').innerText(),/2026-10-25/);
 assert.deepEqual(await page.locator('.scheduled-pick h4').allTextContents(),originalNames);
 const secondWeek=JSON.parse(weekText);secondWeek.week.start='2026-11-02';
 let second=createVisitRecord(JSON.stringify(secondWeek),'Second week.json');
 second=updateVisitRecord(second,'pick-0',{outcome:'went',date:'2026-11-04',note:'PRIVATE other note'});
 const secondPayload={name:'second.json',mimeType:'application/json',buffer:Buffer.from(makeVisitRecordFile(second).text)};
 await page.locator('#visitHistory input').setInputFiles([payload,payload,secondPayload]);
 await page.locator('[data-history-preview]').waitFor({state:'visible'});
 assert.match(await page.locator('[data-history-summary]').innerText(),/1 repeated attendance/);
 assert.equal(await page.locator('[data-history-records] details').count(),3);
 await page.locator('[data-history-records] summary').nth(2).click();
 assert.match(await page.locator('[data-history-records]').innerText(),/2026-11-04/);
 assert.ok(!(await page.locator('[data-history-records]').innerText()).includes('PRIVATE'));
 await page.screenshot({path:'docs/multi-record-history/preview-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-history-preview]').scrollIntoViewIfNeeded();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'docs/multi-record-history/preview-phone.png'});
 await page.setViewportSize({width:1280,height:900});
 assert.ok(!(await page.locator('.prior-visit').innerText()).includes('2 visits'));
 await page.locator('[data-history-use]').click();
 assert.match(await page.locator('.prior-visit').innerText(),/2026-11-04.*2 visits/);
 let conflict=updateVisitRecord(record,'pick-0',{outcome:'did_not_go'});
 await page.locator('#visitHistory input').setInputFiles([payload,{name:'conflict.json',mimeType:'application/json',buffer:Buffer.from(makeVisitRecordFile(conflict).text)}]);
 await page.getByText(/These records disagree/).waitFor();
 assert.equal(await page.locator('[data-history-preview]').isVisible(),false);
 assert.match(await page.locator('.prior-visit').innerText(),/2 visits/);
 await page.locator('#visitHistory input').setInputFiles([payload,secondPayload]);
 await page.locator('[data-history-preview]').waitFor({state:'visible'});
 await page.locator('[data-history-cancel]').click();
 assert.match(await page.locator('.prior-visit').innerText(),/2 visits/);

 const before=requests.length;
 await page.locator('#sampleBtn').click();
 await page.locator('#results').waitFor({state:'visible'});
 assert.equal(await page.locator('.prior-visit').count(),1);
 assert.equal(requests.length,before+1);
 assert.ok(requests.every(r=>!String(r.body).includes('PRIVATE')&&!String(r.body).includes('visits')));
 await page.locator('#visitHistory input').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{}')});
 await page.getByText(/Could not open visit record:/).waitFor();
 assert.equal(await page.locator('.prior-visit').count(),1);
 await page.locator('#weekOrganizer').scrollIntoViewIfNeeded();
 await page.screenshot({path:'docs/multi-record-history/desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('.prior-visit').scrollIntoViewIfNeeded();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'docs/multi-record-history/mobile.png'});
 const saved=page.waitForEvent('download');await page.locator('#saveWeek').click();
 const bytes=await readFile(await (await saved).path(),'utf8');
 assert.ok(!bytes.includes('PRIVATE')&&!bytes.includes('Previously went'));
 await page.locator('[data-history-clear]').click();
 assert.equal(await page.locator('.prior-visit').count(),0);
 await page.reload();
 assert.equal(await page.locator('[data-history-clear]').isDisabled(),true);
 assert.deepEqual(errors,[]);
 await writeFile('docs/multi-record-history/producer-check.json',JSON.stringify({agent:'astra-elm-5b9d13',browser:await browser.version(),checks:['actual fixture app sample and Save week','multiple unfamiliar weeks preview/use; identical overlaps deduped; conflict refused atomically; cancel preserves active context','matching attendance in current and later plan','malformed replacement preserves current context','provider requests exclude attendance and notes','week export excludes attendance and notes','clear and reload remove context','390px no overflow'],errors},null,2));
 console.log('Browser integration passed',await browser.version());
} finally {await browser.close();}
