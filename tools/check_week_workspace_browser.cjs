const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const {chromium} = require(process.env.TASTETABLE_PLAYWRIGHT_MODULE || 'playwright');
const out = process.env.TASTETABLE_EVIDENCE || '/tmp/tastetable-week-workspace';
(async () => {
 await fs.mkdir(out, {recursive:true});
 const browser = await chromium.launch({executablePath:process.env.TASTETABLE_REVIEW_CHROMIUM,headless:true,args:['--no-sandbox']});
 try {
  const page = await browser.newPage({viewport:{width:390,height:844}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.TASTETABLE_REVIEW_URL || 'http://127.0.0.1:8993');
  await page.locator('#sampleBtn').click(); await page.locator('#results').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.activeElement.id==='weekTitle');
  assert.equal(await page.locator('#weekDayNav a').count(),7);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const top=await page.locator('#weekDays').evaluate(e=>e.getBoundingClientRect().top);
  assert.ok(top<800,'first visit appears in first phone viewport');
  await page.screenshot({path:out+'/phone-week.png'});
  const download = async () => {const waiting=page.waitForEvent('download');await page.locator('#saveWeek').click();return JSON.parse(await fs.readFile(await(await waiting).path(),'utf8'));};
  const before=await download();
  await page.locator('#weekDayNav a').nth(4).click();
  assert.match(await page.evaluate(()=>document.activeElement.textContent),/^Friday/);
  const fridayTop=await page.locator('[data-day="Friday"]').evaluate(e=>e.getBoundingClientRect().top);
  assert.ok(fridayTop>=65 && fridayTop<130,'chosen day remains below sticky navigation');
  await page.screenshot({path:out+'/phone-friday.png'});
  await page.locator('[data-evidence-key="pick-0"] summary').click();
  await page.locator('[data-pick-key="pick-0"]').selectOption('Friday');
  await page.waitForFunction(()=>document.querySelector('#weekDayNav a:nth-child(5)').textContent.includes('2 picks'));
  assert.equal(await page.locator('[data-evidence-key="pick-0"]').getAttribute('open'),'');
  await page.locator('#undoWeek').click();
  await page.waitForFunction(()=>document.querySelector('#weekDayNav a:nth-child(5)').textContent.includes('1 pick'));
  const after=await download();assert.deepEqual(after.week,before.week);assert.deepEqual(after.response,before.response);
  await page.locator('[data-pick-key="pick-0"]').selectOption('');
  await page.waitForFunction(()=>document.querySelector('#weekDayNav a').textContent.includes('Open'));
  await page.locator('#resetWeek').click();
  await page.waitForFunction(()=>document.querySelector('#weekDayNav a').textContent.includes('1 pick'));
  await page.locator('#weekDate').fill('2026-12-16');await page.locator('#weekDate').dispatchEvent('change');
  await page.waitForFunction(()=>document.querySelector('#weekDayNav a').getAttribute('aria-label').includes('Dec'));
  const file=out+'/saved-week.json';await fs.writeFile(file,JSON.stringify(before));
  await page.locator('#weekFile').setInputFiles(file);
  await page.waitForFunction(()=>document.activeElement.id==='weekTitle');
  await page.locator('.week-links a[href="#tasteForm"]').click();
  await page.locator('input[name="city"]').fill('New York');
  await page.waitForFunction(()=>document.querySelector('#results').hidden);
  assert.equal(await page.locator('#weekDayNav').isVisible(),false);
  await page.locator('#sampleBtn').click();await page.locator('#results').waitFor({state:'visible'});
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#weekTitle').scrollIntoViewIfNeeded();
  await page.screenshot({path:out+'/desktop-week.png'});
  await page.locator('#weekDayNav a').nth(6).focus();await page.keyboard.press('Enter');
  assert.match(await page.evaluate(()=>document.activeElement.textContent),/^Sunday/);
  assert.deepEqual(errors,[]);
  await fs.writeFile(out+'/receipt.json',JSON.stringify({browser:await browser.version(),firstVisitPhoneTop:top,fridayTop,errors,checks:['actual fixture app entry','accepted-week focus','seven day counts and empty days','native keyboard day navigation','sticky offset','move/undo/omit/reset updates','open evidence preserved','navigation leaves saved response/week unchanged','date updates','saved-week reopen','retired result hides navigation','390px and1440px actual screenshots']},null,2));
  console.log('PASS week workspace actual Chrome');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
