import fs from 'node:fs';
import {spawnSync, execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {dirname, resolve, join} from 'node:path';
import {fileURLToPath} from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const sha = x => createHash('sha256').update(x).digest('hex');
const python = 'C:/Users/minec/AppData/Local/Hamon/hubtwo/runtime/python-3.13.15/python.exe';
const input = join(here, 'baseline-native-result.json');
const week = join(here, 'baseline-saved-week.json');
if (fs.existsSync(input) || fs.existsSync(week)) throw Error('Baseline outputs must be unused.');
const producer = spawnSync(python, ['-B', 'tastetable_cli.py', '--persona', 'mei'], {cwd:root, encoding:'utf8'});
if (producer.status !== 0) throw Error(producer.stderr);
fs.writeFileSync(input, producer.stdout, {flag:'wx'});
const converted = spawnSync(process.execPath, ['tools/native_plan_to_week.mjs', '--input', input, '--week', '2026-10-08', '--output', week], {cwd:root,encoding:'utf8'});
if (converted.status !== 0) throw Error(converted.stderr);
const consumer = spawnSync(process.execPath, ['tools/saved_week_to_html.mjs', '--input', week, '--output', join(here, 'baseline-handoff.html')], {cwd:root,encoding:'utf8'});
const leaves = execFileSync('git', ['ls-files'], {cwd:root,encoding:'utf8'}).trim().split('\n');
const hashes = Object.fromEntries(leaves.map(p => [p,sha(fs.readFileSync(join(root,p)))]));
const receipt = {when:new Date().toISOString(),node:process.version,platform:process.platform,source:execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(),producer:{exit:producer.status,sha256:sha(producer.stdout)},converter:{exit:converted.status,receipt:JSON.parse(converted.stdout),savedWeekSha256:sha(fs.readFileSync(week))},missingConsumer:{exit:consumer.status,stderr:consumer.stderr,outputPresent:fs.existsSync(join(here,'baseline-handoff.html'))},sourceLeaves:leaves.length,sourceHashes:hashes};
fs.writeFileSync(join(here,'baseline.json'),JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({source:receipt.source,producerExit:producer.status,converterExit:converted.status,missingConsumerExit:consumer.status,missingConsumer:consumer.stderr.includes('MODULE_NOT_FOUND'),sourceLeaves:leaves.length,savedWeekSha256:receipt.converter.savedWeekSha256}));
